-- 1. CLIENTE_TELEFONO -> CLIENTE
ALTER TABLE "CLIENTE_TELEFONO"
  DROP CONSTRAINT IF EXISTS "CLIENTE_TELEFONO_ID_CLIENTE_fkey",
  DROP CONSTRAINT IF EXISTS "client_telefono_id_cliente_fkey",
  DROP CONSTRAINT IF EXISTS "fk_cliente_telefono_cliente",
  ADD CONSTRAINT "fk_cliente_telefono_cliente"
  FOREIGN KEY ("ID_CLIENTE") 
  REFERENCES "CLIENTE" ("ID_CLIENTE")
  ON DELETE CASCADE
  ON UPDATE CASCADE;

